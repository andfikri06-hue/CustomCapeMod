#!/usr/bin/env python3
"""Converts a compiled .dex file into a C++ header with the bytes
hex-encoded as a string constant, for embedding + loading at runtime via
dalvik.system.InMemoryDexClassLoader (see CapeCanvasBridge.cpp).

Usage: generate_embedded_dex_header.py <input.dex> <output.h>
"""
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: generate_embedded_dex_header.py <input.dex> <output.h>", file=sys.stderr)
        return 1

    dex_path, header_path = sys.argv[1], sys.argv[2]

    with open(dex_path, "rb") as f:
        dex_bytes = f.read()
    hex_str = dex_bytes.hex()

    chunk_size = 100
    chunks = [hex_str[i:i + chunk_size] for i in range(0, len(hex_str), chunk_size)]

    with open(header_path, "w") as f:
        f.write("// AUTO-GENERATED by scripts/generate_embedded_dex_header.py\n")
        f.write("// during the CI build - do not edit by hand, do not commit.\n")
        f.write("#pragma once\n\n")
        f.write("namespace customcape {\n\n")
        f.write("// Hex-encoded bytes of CapeDownloadHelper.dex ({} bytes raw).\n".format(len(dex_bytes)))
        f.write("inline constexpr char kCapeDownloadHelperDexHex[] =\n")
        for chunk in chunks:
            f.write('    "{}"\n'.format(chunk))
        f.write("    ;\n\n")
        f.write("} // namespace customcape\n")

    print("Wrote {} ({} hex chars from {} dex bytes)".format(header_path, len(hex_str), len(dex_bytes)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
  
